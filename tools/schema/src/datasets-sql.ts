/**
 * The runtime catalogue in the database (see runtime-catalogue.ts for what goes where). Per tenant:
 *   aip.runtime_dataset        each runtime dataset's layout: its structure and values, references in place of tables
 *   aip.runtime_sheet          each catalogue sheet, once, by name
 *   aip.runtime_sheet_group    for a sheet holding a family of like lists: each list's key and its rows' range
 *   aip.runtime_sheet_block    each sheet's rows, in order, as compressed json blocks
 *   aip.runtime_sheet_rows     a view with one row per record (sheet, ordinal, group, record), for reading and checks
 * Tables that are copies of governed sheets are not held here at all: layouts refer to the governed sheet.
 *
 * Rows and layouts are stored as json, not jsonb: json keeps the text as written, so keys keep their order and every
 * screen receives its data in the shape it was built against. Members read; nothing in the application writes: the
 * data is loaded with the server's rights (the seed, run with the service role). Each write statement is audited once
 * per tenant with what it touched, rather than one audit row per record.
 *
 * supabase/migrations/20261009000100_aip_runtime_datasets.sql (the first, part-per-table store) is applied history and
 * kept as it was; firstStoreRetirementSql() removes its tables now that the build reading the catalogue is live.
 */
import type { Json } from "../../../packages/host-bridge/src/dataset-parts.ts";
import type { Catalogue } from "./runtime-catalogue.ts";
import { literal } from "./seed-sql.ts";

const TABLES = ["runtime_dataset", "runtime_sheet", "runtime_sheet_group", "runtime_sheet_block"];

export function catalogueSql(): string {
  return `-- Sustantix AIP · the runtime catalogue: each runtime dataset's layout and every sheet it uses, once, by name
-- Generated by tools/schema from src/datasets-sql.ts — do not edit by hand.

-- The first store (aip.dataset_part / aip.dataset_block, one entry per table) stays until the build that reads this
-- catalogue is live; a later migration removes it, so no deployment is ever without the tables it reads.

create table if not exists aip.runtime_dataset (
  tenant_id uuid not null references aip.tenants(id) on delete cascade,
  dataset text not null check (dataset ~ '^[0-9a-f]{16}$'),
  label text not null check (length(label) between 1 and 200),
  layout json not null,
  bytes integer not null check (bytes > 0),
  updated_at timestamptz not null default now(),
  primary key (tenant_id, dataset)
);

create table if not exists aip.runtime_sheet (
  tenant_id uuid not null references aip.tenants(id) on delete cascade,
  sheet text not null check (length(sheet) between 1 and 300),
  row_count integer not null check (row_count >= 0),
  bytes bigint not null check (bytes >= 0),
  -- Where the sheet is used: "<dataset label> <JSON Pointer>" of each table it holds.
  used_by text[] not null default '{}',
  updated_at timestamptz not null default now(),
  primary key (tenant_id, sheet)
);

create table if not exists aip.runtime_sheet_group (
  tenant_id uuid not null,
  sheet text not null,
  group_key text not null,
  first_ordinal integer not null check (first_ordinal >= 0),
  row_count integer not null check (row_count >= 0),
  primary key (tenant_id, sheet, group_key),
  foreign key (tenant_id, sheet) references aip.runtime_sheet(tenant_id, sheet) on delete cascade
);

create table if not exists aip.runtime_sheet_block (
  tenant_id uuid not null,
  sheet text not null,
  first_ordinal integer not null check (first_ordinal >= 0),
  row_count integer not null check (row_count > 0),
  bytes integer not null check (bytes > 0),
  rows json not null,
  primary key (tenant_id, sheet, first_ordinal),
  foreign key (tenant_id, sheet) references aip.runtime_sheet(tenant_id, sheet) on delete cascade
);
alter table aip.runtime_sheet_block alter column rows set compression lz4;

${TABLES.map(
  (t) => `alter table aip.${t} enable row level security;
drop policy if exists p_read on aip.${t};
create policy p_read on aip.${t} for select to authenticated using (aip.has_role(tenant_id));`,
).join("\n")}
-- Read-only for members: writes come from the seed or the server.
revoke all on ${TABLES.map((t) => `aip.${t}`).join(", ")} from authenticated;
grant select on ${TABLES.map((t) => `aip.${t}`).join(", ")} to authenticated;
grant all on ${TABLES.map((t) => `aip.${t}`).join(", ")} to service_role;

-- One record per row, for reading a sheet in SQL (the caller's rights apply).
create or replace view aip.runtime_sheet_rows with (security_invoker = true) as
  select b.tenant_id, b.sheet, b.first_ordinal + e.n::integer - 1 as ordinal, g.group_key, e.record
  from aip.runtime_sheet_block b
  cross join lateral json_array_elements(b.rows) with ordinality as e(record, n)
  left join aip.runtime_sheet_group g
    on g.tenant_id = b.tenant_id and g.sheet = b.sheet
   and b.first_ordinal + e.n::integer - 1 >= g.first_ordinal and b.first_ordinal + e.n::integer - 1 < g.first_ordinal + g.row_count;
grant select on aip.runtime_sheet_rows to authenticated;

-- One audit entry per statement and tenant: which datasets or sheets, and how many entries, were written or removed.
create or replace function aip.audit_runtime_write() returns trigger language plpgsql security definer set search_path = aip, pg_temp as $$
begin
  if tg_op = 'DELETE' then
    insert into aip.audit_log(tenant_id, actor, action, entity, entity_key, before, after)
    select o.tenant_id, auth.uid(), 'delete', tg_table_name, null, jsonb_build_object('records', count(*)), null
    from old_rows o group by o.tenant_id;
  else
    insert into aip.audit_log(tenant_id, actor, action, entity, entity_key, before, after)
    select n.tenant_id, auth.uid(), lower(tg_op), tg_table_name, null, null, jsonb_build_object('records', count(*))
    from new_rows n group by n.tenant_id;
  end if;
  return null;
end $$;
revoke all on function aip.audit_runtime_write() from public, anon, authenticated;
${TABLES.flatMap((t) => [
  `drop trigger if exists t_audit_insert on aip.${t};`,
  `create trigger t_audit_insert after insert on aip.${t} referencing new table as new_rows for each statement execute function aip.audit_runtime_write();`,
  `drop trigger if exists t_audit_update on aip.${t};`,
  `create trigger t_audit_update after update on aip.${t} referencing new table as new_rows for each statement execute function aip.audit_runtime_write();`,
  `drop trigger if exists t_audit_delete on aip.${t};`,
  `create trigger t_audit_delete after delete on aip.${t} referencing old table as old_rows for each statement execute function aip.audit_runtime_write();`,
]).join("\n")}

-- Several blocks in one call: p_blocks is [{"s": sheet, "f": first_ordinal}, …]; the answer is each block's rows (a json
-- array, as stored), in the order asked; a block the caller may not read answers null.
create or replace function aip.runtime_sheet_blocks(p_tenant uuid, p_blocks jsonb)
returns json language sql stable security invoker set search_path = aip, pg_temp as $$
  select coalesce(json_agg((
    select b.rows from aip.runtime_sheet_block b
    where b.tenant_id = p_tenant and b.sheet = s.value->>'s' and b.first_ordinal = (s.value->>'f')::integer
  ) order by s.ordinality), '[]'::json)
  from jsonb_array_elements(p_blocks) with ordinality as s(value, ordinality);
$$;
revoke all on function aip.runtime_sheet_blocks(uuid, jsonb) from public, anon;
grant execute on function aip.runtime_sheet_blocks(uuid, jsonb) to authenticated, service_role;
`;
}

/** Removes the first store (one entry per table), which nothing reads since the catalogue build went live. */
export function firstStoreRetirementSql(): string {
  return `-- Sustantix AIP · retire the first runtime-data store; the runtime catalogue (20261010000100) replaces it
-- Generated by tools/schema from src/datasets-sql.ts — do not edit by hand.

-- Its policies and audit triggers go with the tables; the audit log keeps what was written to them.
drop function if exists aip.dataset_blocks(uuid, jsonb);
drop table if exists aip.dataset_block, aip.dataset_part;
drop function if exists aip.audit_dataset_write();
`;
}

/** A sheet's rows as consecutive json-array blocks of about blockBytes of text each (at least one row per block). */
export function blocksOf(rows: readonly Json[], blockBytes: number): Array<{ first: number; count: number; text: string }> {
  const out: Array<{ first: number; count: number; text: string }> = [];
  let texts: string[] = [];
  let size = 0;
  let first = 0;
  rows.forEach((r, i) => {
    const t = JSON.stringify(r);
    if (texts.length && size + t.length > blockBytes) {
      out.push({ first, count: texts.length, text: `[${texts.join(",")}]` });
      texts = [];
      size = 0;
      first = i;
    }
    texts.push(t);
    size += t.length + 1;
  });
  if (texts.length) out.push({ first, count: texts.length, text: `[${texts.join(",")}]` });
  return out;
}

export const BLOCK_BYTES = 256_000;

/** Statements that replace one tenant's runtime catalogue (idempotent: run twice, same result). */
export function catalogueSeedSql(tenantId: string, c: Catalogue, blockBytes = BLOCK_BYTES): string[] {
  const t = literal(tenantId);
  const out: string[] = [`delete from aip.runtime_dataset where tenant_id = ${t};`, `delete from aip.runtime_sheet where tenant_id = ${t};`];
  for (const d of c.datasets) {
    if (!/^[0-9a-f]{16}$/.test(d.id)) throw new Error(`dataset id ${d.id} is not a runtime dataset id`);
    const text = JSON.stringify(d.layout);
    out.push(`insert into aip.runtime_dataset(tenant_id, dataset, label, layout, bytes) values (${t}, ${literal(d.id)}, ${literal(d.label)}, ${literal(text)}::json, ${text.length});`);
  }
  for (const s of c.sheets) {
    const blocks = blocksOf(s.rows, blockBytes);
    const usedBy = `array[${s.usedBy.map(literal).join(",")}]::text[]`;
    out.push(`insert into aip.runtime_sheet(tenant_id, sheet, row_count, bytes, used_by) values (${t}, ${literal(s.name)}, ${s.rows.length}, ${blocks.reduce((n, b) => n + b.text.length, 0)}, ${usedBy});`);
    if (s.groups?.length) out.push(`insert into aip.runtime_sheet_group(tenant_id, sheet, group_key, first_ordinal, row_count) values\n${s.groups.map((g) => `(${t}, ${literal(s.name)}, ${literal(g.key)}, ${g.first}, ${g.count})`).join(",\n")};`);
    for (const b of blocks) out.push(`insert into aip.runtime_sheet_block(tenant_id, sheet, first_ordinal, row_count, bytes, rows) values (${t}, ${literal(s.name)}, ${b.first}, ${b.count}, ${b.text.length}, ${literal(b.text)}::json);`);
  }
  return out;
}
