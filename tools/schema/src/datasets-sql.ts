/**
 * Runtime datasets in the database. Every dataset the runtime reads that is tenant data (not product content: help,
 * dictionaries, rules, configuration) is held per tenant: its frame (the dataset with each table replaced by a
 * reference) in aip.dataset_part, and each table's rows in aip.dataset_block, in their original order, as compressed blocks.
 * The host joins them back after sign-in (packages/host-bridge/src/dataset-parts.ts), so no tenant data ships with
 * the application.
 *
 * Rows and frames are stored as json, not jsonb: json keeps the text as written, so keys keep their order and every
 * screen receives exactly the value it was built against. Members read; nothing in the application writes: the data
 * is loaded with the server's rights (the seed, run with the service role). Each write statement is
 * audited once per tenant with what it touched, rather than one audit row per record.
 */
import { joinDataset, splitDataset, type Json } from "../../../packages/host-bridge/src/dataset-parts.ts";
import { literal } from "./seed-sql.ts";

export function datasetsSql(): string {
  return `-- Sustantix AIP · runtime datasets held per tenant (database-only data)
-- Generated by tools/schema from src/datasets-sql.ts — do not edit by hand.

create table if not exists aip.dataset_part (
  tenant_id uuid not null references aip.tenants(id) on delete cascade,
  dataset text not null check (dataset ~ '^[0-9a-f]{16}$'),
  -- JSON Pointer of the table within its dataset ('' when the dataset is itself a table); '$frame' is the frame.
  part text not null check (part = '$frame' or part = '' or (part like '/%' and length(part) <= 1024)),
  frame json,
  row_count integer not null default 0 check (row_count >= 0),
  bytes bigint not null default 0 check (bytes >= 0),
  updated_at timestamptz not null default now(),
  primary key (tenant_id, dataset, part),
  check ((part = '$frame') = (frame is not null))
);

-- A table's rows in consecutive blocks (first_ordinal, first_ordinal + row_count): each block is one json array, which
-- the database compresses, so a tenant's runtime data takes a fraction of its text size.
create table if not exists aip.dataset_block (
  tenant_id uuid not null,
  dataset text not null,
  part text not null,
  first_ordinal integer not null check (first_ordinal >= 0),
  row_count integer not null check (row_count > 0),
  bytes integer not null check (bytes > 0),
  rows json not null,
  primary key (tenant_id, dataset, part, first_ordinal),
  foreign key (tenant_id, dataset, part) references aip.dataset_part(tenant_id, dataset, part) on delete cascade
);
alter table aip.dataset_block alter column rows set compression lz4;

alter table aip.dataset_part enable row level security;
alter table aip.dataset_block enable row level security;
drop policy if exists p_read on aip.dataset_part;
create policy p_read on aip.dataset_part for select to authenticated using (aip.has_role(tenant_id));
drop policy if exists p_read on aip.dataset_block;
create policy p_read on aip.dataset_block for select to authenticated using (aip.has_role(tenant_id));
-- Read-only for members: writes come from the seed or the server.
revoke all on aip.dataset_part, aip.dataset_block from authenticated;
grant select on aip.dataset_part, aip.dataset_block to authenticated;
grant all on aip.dataset_part, aip.dataset_block to service_role;

-- One audit entry per statement and tenant: which datasets and how many parts or blocks were written or removed.
create or replace function aip.audit_dataset_write() returns trigger language plpgsql security definer set search_path = aip, pg_temp as $$
begin
  if tg_op = 'DELETE' then
    insert into aip.audit_log(tenant_id, actor, action, entity, entity_key, before, after)
    select o.tenant_id, auth.uid(), 'delete', tg_table_name, null,
           jsonb_build_object('datasets', jsonb_agg(distinct o.dataset), 'records', count(*)), null
    from old_rows o group by o.tenant_id;
  else
    insert into aip.audit_log(tenant_id, actor, action, entity, entity_key, before, after)
    select n.tenant_id, auth.uid(), lower(tg_op), tg_table_name, null,
           null, jsonb_build_object('datasets', jsonb_agg(distinct n.dataset), 'records', count(*))
    from new_rows n group by n.tenant_id;
  end if;
  return null;
end $$;
revoke all on function aip.audit_dataset_write() from public, anon, authenticated;
${["dataset_part", "dataset_block"]
  .flatMap((t) => [
    `drop trigger if exists t_audit_insert on aip.${t};`,
    `create trigger t_audit_insert after insert on aip.${t} referencing new table as new_rows for each statement execute function aip.audit_dataset_write();`,
    `drop trigger if exists t_audit_update on aip.${t};`,
    `create trigger t_audit_update after update on aip.${t} referencing new table as new_rows for each statement execute function aip.audit_dataset_write();`,
    `drop trigger if exists t_audit_delete on aip.${t};`,
    `create trigger t_audit_delete after delete on aip.${t} referencing old table as old_rows for each statement execute function aip.audit_dataset_write();`,
  ])
  .join("\n")}

-- Several blocks in one call: p_blocks is [{"d": dataset, "p": part, "f": first_ordinal}, …]; the answer is each
-- block's rows (a json array, as stored), in the order asked; a block the caller may not read answers null.
create or replace function aip.dataset_blocks(p_tenant uuid, p_blocks jsonb)
returns json language sql stable security invoker set search_path = aip, pg_temp as $$
  select coalesce(json_agg((
    select b.rows from aip.dataset_block b
    where b.tenant_id = p_tenant and b.dataset = s.value->>'d' and b.part = s.value->>'p' and b.first_ordinal = (s.value->>'f')::integer
  ) order by s.ordinality), '[]'::json)
  from jsonb_array_elements(p_blocks) with ordinality as s(value, ordinality);
$$;
revoke all on function aip.dataset_blocks(uuid, jsonb) from public, anon;
grant execute on function aip.dataset_blocks(uuid, jsonb) to authenticated, service_role;
`;
}

/** The part that holds a dataset's frame (a table's part is its JSON Pointer, which is never this). */
export const FRAME_PART = "$frame";

/**
 * Statements that replace one tenant's runtime datasets with the given ones (idempotent: run twice, same result).
 * Each table's rows go in as blocks of about blockBytes of text, in order.
 */
export function datasetSeedSql(tenantId: string, datasets: ReadonlyArray<{ id: string; value: Json }>, blockBytes = 256_000): string[] {
  const out: string[] = [`delete from aip.dataset_part where tenant_id = ${literal(tenantId)};`];
  for (const { id, value } of datasets) {
    if (!/^[0-9a-f]{16}$/.test(id)) throw new Error(`dataset id ${id} is not a runtime dataset id`);
    const { frame, tables } = splitDataset(value);
    // The stored parts must rebuild the dataset exactly before anything is written.
    const rebuilt = joinDataset(JSON.parse(JSON.stringify(frame)) as Json, new Map(tables.map((t) => [t.part, t.rows])));
    if (JSON.stringify(rebuilt) !== JSON.stringify(value)) throw new Error(`dataset ${id} does not rebuild from its parts`);
    const frameText = JSON.stringify(frame);
    const blocks = tables.map((t) => ({ part: t.part, blocks: blocksOf(t.rows, blockBytes) }));
    const parts = [`(${literal(tenantId)}, ${literal(id)}, ${literal(FRAME_PART)}, ${literal(frameText)}::json, 0, ${frameText.length})`];
    for (const t of blocks) {
      parts.push(`(${literal(tenantId)}, ${literal(id)}, ${literal(t.part)}, null, ${t.blocks.reduce((n, b) => n + b.count, 0)}, ${t.blocks.reduce((n, b) => n + b.text.length, 0)})`);
    }
    out.push(`insert into aip.dataset_part(tenant_id, dataset, part, frame, row_count, bytes) values\n${parts.join(",\n")};`);
    for (const t of blocks) {
      for (const b of t.blocks) {
        out.push(`insert into aip.dataset_block(tenant_id, dataset, part, first_ordinal, row_count, bytes, rows) values (${literal(tenantId)}, ${literal(id)}, ${literal(t.part)}, ${b.first}, ${b.count}, ${b.text.length}, ${literal(b.text)}::json);`);
      }
    }
  }
  return out;
}

/** A table's rows as consecutive json-array blocks of about blockBytes of text each (at least one row per block). */
export function blocksOf(rows: Json[], blockBytes: number): Array<{ first: number; count: number; text: string }> {
  const out: Array<{ first: number; count: number; text: string }> = [];
  let texts: string[] = [];
  let size = 0;
  let first = 0;
  rows.forEach((r, i) => {
    const t = JSON.stringify(r);
    if (texts.length && size + t.length > blockBytes) {
      out.push({ first, count: texts.length, text: `[${texts.join(",")}]` });
      texts = [];
      size = 0;
      first = i;
    }
    texts.push(t);
    size += t.length + 1;
  });
  if (texts.length) out.push({ first, count: texts.length, text: `[${texts.join(",")}]` });
  return out;
}
